import type { DamageType } from '../core/types.ts';

export type SkillTag =
  | 'attack'
  | 'spell'
  | 'projectile'
  | 'melee'
  | 'aoe'
  | 'duration'
  | 'minion'
  | 'physical'
  | 'fire'
  | 'cold'
  | 'lightning'
  | 'chaos'
  | 'channelled'
  | 'buff'
  | 'movement';

export type SkillBehavior =
  | 'melee_hit'
  | 'projectile'
  | 'nova'
  | 'summon'
  | 'self_buff'
  | 'ground_aoe'
  | 'dash';

export interface SkillDef {
  id: string;
  name: string;
  desc: string;
  tags: SkillTag[];
  behavior: SkillBehavior;
  damageType: DamageType;
  /** % of base weapon/spell damage this hit deals, before "increased"/"more" modifiers. */
  effectiveness: number;
  baseDamageMin: number;
  baseDamageMax: number;
  manaCost: number;
  spiritReserve?: number; // for persistent/aura-like skills
  cooldown: number;
  castTime: number; // seconds
  requiredAttr: { strength?: number; dexterity?: number; intelligence?: number };
  levelReq: number;
  // behavior params
  projectileCount?: number;
  projectileSpeed?: number;
  spreadDeg?: number;
  pierce?: boolean;
  chain?: number;
  radius?: number;
  range?: number;
  summonId?: string;
  summonCount?: number;
  buffStats?: Record<string, number>;
  buffDuration?: number;
  dashDistance?: number;
}

