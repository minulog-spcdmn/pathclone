export type SupportTag = 'damage' | 'projectile' | 'aoe' | 'speed' | 'utility' | 'minion';

export interface SupportDef {
  id: string;
  name: string;
  desc: string;
  /** Only applies if the linked skill has at least one of these tags (empty = always applies). */
  requiresTags: SkillTag[];
  manaMultiplier: number; // e.g. 1.3 = 30% more mana cost
  statMods: Record<string, number>; // added to the skill's effective damage/behavior calc
  moreMultiplier?: number; // "more" damage multiplier (%), applies multiplicatively
  levelReq: number;
}

